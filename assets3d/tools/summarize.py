#!/usr/bin/env python3
"""Collect every number the docs quote into assets3d/dist/summary.json and write assets3d/RESULTS.md (generated; never edit by hand).

  python3 assets3d/tools/summarize.py

Reads: dist/*/*.sprites.json · dist/verification.json · dist/pins_verification.json · dist/cars_verification.json · dist/validation*.json ·
       dist/tuning/*.json · preview/*.metrics.json · ../design/tokens/CONTRAST.md
"""
import glob
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
A3D = os.path.normpath(os.path.join(HERE, ".."))
DIST = os.path.join(A3D, "dist")
REPO = os.path.normpath(os.path.join(A3D, ".."))


def jl(path, default=None):
    return json.load(open(path)) if os.path.exists(path) else default


def kib(n):
    return f"{n / 1024:,.0f}"


assets = {}
for mp in sorted(glob.glob(os.path.join(DIST, "*", "*.sprites.json"))):
    m = jl(mp)
    stem = m["asset"] + (("_" + m["variant"]) if m["variant"] else "")
    assets[stem] = m

ver = []
for f in ("verification.json", "pins_verification.json", "cars_verification.json"):
    ver += jl(os.path.join(DIST, f), [])
tuning = {os.path.basename(p)[len("tune_h_"):-5]: jl(p) for p in sorted(glob.glob(os.path.join(DIST, "tuning", "tune_h_*.json")))}
sweep = jl(os.path.join(DIST, "tuning", "pitch_sweep_arrow.json"))
validation = {os.path.basename(p)[len("validation_"):-5]: jl(p) for p in sorted(glob.glob(os.path.join(DIST, "validation_*.json")))}
if not validation and os.path.exists(os.path.join(DIST, "validation.json")):
    validation = {"arrow": jl(os.path.join(DIST, "validation.json"))}
pop = {os.path.basename(p)[len("runtime_flip_metrics_"):-5]: jl(p) for p in sorted(glob.glob(os.path.join(DIST, "tuning", "runtime_flip_metrics_*.json")))}
contrast_rows = []
cp = os.path.join(REPO, "design", "tokens", "CONTRAST.md")
if os.path.exists(cp):
    for line in open(cp):
        if line.startswith("| pin "):
            c = [x.strip() for x in line.strip().strip("|").split("|")]
            contrast_rows.append(c)

summary = {"assets": {}, "verification": ver, "validation": validation, "tuning": tuning, "pitch_sweep": sweep, "popping": pop}
for stem, m in assets.items():
    n = len(m["pitches"]) * m["yaws"]
    rp = m.get("reprojection") or {}
    summary["assets"][stem] = {"kind": m.get("kind", "solid"), "frames": n, "pitches": m["pitches"], "yaws": m["yaws"], "frame_dp": m["frame_dp"], "unit_dp": m["unit_dp"],
                               "tiers_kib": {t: round(v["total_bytes"] / 1024, 1) for t, v in m["tiers"].items()}, "reprojection": rp or None,
                               "samples": m["source"]["samples"], "renderer": m["source"]["renderer"]}
json.dump(summary, open(os.path.join(DIST, "summary.json"), "w"), indent=1)

L = []
w = L.append
w("# Results (generated)")
w("")
w("> Generated by `assets3d/tools/summarize.py` from the pipeline's own output (`dist/*.sprites.json`, `dist/*verification.json`, `dist/tuning/*`). Do not edit by hand.")
w("")
w("## 1 · Assets and sizes")
w("")
w("| Asset | Kind | Frames (pitches × yaws) | Frame (dp) | xhdpi (KiB) | xxhdpi (KiB) | xxxhdpi (KiB) | Blender | Samples |")
w("|---|---|---:|---:|---:|---:|---:|---|---:|")
for stem, m in assets.items():
    t = m["tiers"]
    w(f"| `{stem}` | {m.get('kind', 'solid')} | {len(m['pitches']) * m['yaws']} ({len(m['pitches'])} × {m['yaws']}) | {m['frame_dp']} | " + " | ".join(kib(t[x]["total_bytes"]) if x in t else "–" for x in ("xhdpi", "xxhdpi", "xxxhdpi")) + f" | {m['source']['renderer'].split(' ')[0]} {m['source']['renderer'].split(' ')[1]} | {m['source']['samples']} |")
tot = {x: sum(m["tiers"][x]["total_bytes"] for m in assets.values() if x in m["tiers"]) for x in ("xhdpi", "xxhdpi", "xxxhdpi")}
w(f"| **all** | | **{sum(len(m['pitches']) * m['yaws'] for m in assets.values())}** | | **{kib(tot['xhdpi'])}** | **{kib(tot['xxhdpi'])}** | **{kib(tot['xxxhdpi'])}** | | |")
w("")
w("A device downloads one density tier. Pins are tiny; the pointer family is the bulk, and vehicle skins are intended as on-demand packs.")
w("")
w("## 2 · Reconstruction quality of off-grid views")
w("")
w("The runtime blends the two pitch buckets that bracket the camera pitch, each warped to the true view by one affine matrix. **Outline** = the lowest 20 % of the mesh height (rim, footprint, wheels: the high-contrast silhouette); **all vertices** also includes raised parts (the arrow's ridge, a car's roof). The dp errors are geometric, for the single-bucket fallback (blending improves on them), worst case over every pitch 0–60° and every heading. **Image** = alpha-weighted PSNR against true Blender renders of off-grid views (mid-bucket pitches × half-step yaws, the worst case on both axes).")
w("")
w("| Asset | Plane h (u) | Outline worst / p95 (dp) | All vertices worst / p95 (dp) | Image PSNR mean / min (dB) | Pop: pitch crossing / heading flip (RMS) |")
w("|---|---:|---:|---:|---:|---:|")
for stem, m in assets.items():
    rp = m.get("reprojection")
    if not rp:
        continue
    im = rp.get("image")
    w(f"| `{stem}` | {rp['plane_h_u']:.2f} | {rp['base_worst_err_dp']:.2f} / {rp['base_p95_err_dp']:.2f} | {rp['worst_err_dp']:.2f} / {rp['p95_err_dp']:.2f} | " + (f"{im['psnr_mean_db']:.1f} / {im['psnr_min_db']:.1f} ({im['views']} views)" if im else "not calibrated") + " | " + (f"{im.get('pitch_pop_rms_max', im['switch_pop_rms_max']):.4f} / {im.get('yaw_pop_rms_max', float('nan')):.4f}" if im else "–") + " |")
w("")
w("Top-down (pitch 0°) is exact for any heading: an in-plane rotation of a top-down sprite loses nothing.")
w("")
if validation:
    w("### 2.1 Which reconstruction strategy? (mean PSNR in dB vs true renders of off-grid views)")
    w("")
    names = list(next(iter(validation.values()))["psnr_db_vs_true_render"].keys())
    w("| Asset (views) | " + " | ".join(n.split(". ", 1)[0] + ". " + n.split(". ", 1)[1].replace("two buckets, each warped at h*, blended by pitch", "two buckets warped at h*, blended") for n in names) + " |")
    w("|---|" + "---:|" * len(names))
    for a_, v in validation.items():
        r = v["psnr_db_vs_true_render"]
        w(f"| `{a_}` ({len(v['views'])}) | " + " | ".join(f"{r[n]['mean']:.1f}" + (f" ({r[n]['min']:.1f})" if n.startswith(("D.", "E.")) else "") for n in names) + " |")
    w("")
    w("Values in parentheses are the worst view. **E** (the shipped strategy): warp each of the two pitch buckets that bracket the camera pitch to the true view with one affine matrix, then blend by the pitch fraction.")
    w("")
if tuning:
    w("### 2.2 Choosing the plane height `h` in image space")
    w("")
    for key, t in tuning.items():
        if len(t["candidates"]) < 2:
            continue
        w(f"**`{t['asset']}`, strategy `{t.get('strategy', 'single')}`** — {len(t['pitch_buckets'])} pitch buckets, {t['views']} views")
        w("")
        w("| h (u) | PSNR mean (dB) | PSNR min (dB) | Pitch-crossing pop (RMS, × smooth) | Heading-flip pop (RMS, × smooth) |")
        w("|---:|---:|---:|---:|---:|")
        best = t["chosen_h_u"]
        for h, c in t["candidates"].items():
            mark = " **← chosen**" if abs(float(h) - best) < 1e-9 else ""
            pp = c.get("pitch_pop_max_rms", c["pop_max_rms"])
            yp = c.get("yaw_pop_max_rms")
            w(f"| {float(h):g}{mark} | {c['psnr_mean']:.2f} | {c['psnr_min']:.1f} | {pp:.4f} ({c.get('pitch_pop_ratio', c.get('pop_ratio', 0)):.1f}×) | " + (f"{yp:.4f} ({c['yaw_pop_ratio']:.1f}×)" if yp is not None else "–") + " |")
        w("")
    sg = tuning.get("arrow_single", {}).get("chosen")
    bl = tuning.get("arrow_blend", {}).get("chosen")
    if sg and bl and sg.get("pitch_pop_max_rms") is not None:
        w(f"**Single bucket vs blend at the chosen h (`arrow`):** PSNR {sg['psnr_mean']:.1f} → {bl['psnr_mean']:.1f} dB mean ({sg['psnr_min']:.1f} → {bl['psnr_min']:.1f} min); pitch-crossing pop {sg['pitch_pop_max_rms']:.4f} → {bl['pitch_pop_max_rms']:.4f} RMS ({sg['pitch_pop_max_rms'] / bl['pitch_pop_max_rms']:.1f}× lower).")
        w("")
    ab = tuning.get("arrow_blend")
    if ab and "0.5" in ab["candidates"]:
        c5, cb = ab["candidates"]["0.5"], ab["chosen"]
        w(f"For the arrow, minimising the *geometric* maximum vertex error (`reproject_error.py` without `--h`) chooses h = 0.5 u. In image space that plane scores {c5['psnr_mean']:.1f} dB against {cb['psnr_mean']:.1f} dB at the chosen {ab['chosen_h_u']:g} u (rows above): the criterion over-weights the interior ridge, while the eye is dominated by the outline.")
        w("")
if sweep:
    w("### 2.3 Pitch-bucket spacing (`arrow`, 24 yaws, geometry only, at the chosen h)")
    w("")
    w("| Pitch spacing | Buckets | Frames | Outline worst (dp) | All-vertex worst (dp) | Outline pop (dp) | All-vertex pop (dp) |")
    w("|---:|---:|---:|---:|---:|---:|---:|")
    for sp, r in sweep["by_spacing"].items():
        w(f"| {float(sp):g}° | {r['buckets']} | {r['frames']} | {r['outline']['worst_dp']:.2f} | {r['all_vertices']['worst_dp']:.2f} | {r['outline']['pop_dp']:.2f} | {r['all_vertices']['pop_dp']:.2f} |")
    w("")
    w("The visible outline stays under 1 dp at every spacing; a finer grid buys lower ridge error and smaller switch pops. The arrow ships at 7.5°; the secondary car skins use 15°.")
    w("")
if pop:
    w("### 2.4 Heading-bucket flips in motion (`simulate_runtime.py metrics`)")
    w("")
    w("The same 14 s camera programme as the video (pitch 60° → 0° → 45°, heading-up with a lagging camera, then north-up), run headless. RMS change of the drawn sprite between consecutive frames: the **motion floor** is frames without a heading flip (real rotation in turns included); **flip frames** are where the nearest heading bucket changes, for a hard switch and for the optional ~100 ms dissolve.")
    w("")
    w("| Asset | Frames | Flips | Motion floor median / p95 / max | Flip frames, hard: mean / max | Flip frames, dissolve: mean / max |")
    w("|---|---:|---:|---:|---:|---:|")
    for k, v in pop.items():
        f, fl = v["motion_floor_rms"], v["flip_frame_rms"]
        w(f"| `{k}` | {v['frames']} | {v['heading_flips']} | {f['median']:.4f} / {f['p95']:.4f} / {f['max']:.4f} | {fl['hard']['mean']:.4f} / {fl['hard']['max']:.4f} | {fl['dissolve']['mean']:.4f} / {fl['dissolve']['max']:.4f} |")
    w("")
    w("A flip changes the sprite by about as much as one frame of real rotation in a turn (the flip mean sits near the p95 of ordinary motion frames), because flips only happen while turning. The dissolve lowers the mean change at flip frames by roughly 30 %; its maximum is set by the rotation itself. It is cheap but optional.")
    w("")
w("## 3 · Pin palette (contrast audited)")
w("")
if contrast_rows:
    w("| Pin | Glyph | Badge | Ratio | Min | Result |")
    w("|---|:---:|:---:|---:|---:|:---:|")
    for c in contrast_rows:
        w(f"| {c[0].replace('pin ', '').replace(': glyph on badge', '')} | {c[1]} | {c[2]} | {c[3]} | {c[4]} | {c[5]} |")
    w("")
w("## 4 · Verification")
w("")
by = {}
for r in ver:
    by.setdefault(r["scope"], []).append(r)
w("| Scope | Checks | Passed | Required failures |")
w("|---|---:|---:|---:|")
for scope, rs in by.items():
    w(f"| `{scope}` | {len(rs)} | {sum(1 for r in rs if r['pass'])} | {sum(1 for r in rs if r['required'] and not r['pass'])} |")
w(f"| **all** | **{len(ver)}** | **{sum(1 for r in ver if r['pass'])}** | **{sum(1 for r in ver if r['required'] and not r['pass'])}** |")
w("")
for scope in [s for s in by if s in ("arrow", "selftest", "calib") or s.startswith("car_sedan")][:3]:
    w(f"<details><summary>Every check for <code>{scope}</code></summary>")
    w("")
    w("| Check | Result | Detail |")
    w("|---|:---:|---|")
    for r in by[scope]:
        w(f"| {r['check']} | {'✅' if r['pass'] else ('❌' if r['required'] else '⚠️')} | {r['detail'].replace('|', '\\|')} |")
    w("")
    w("</details>")
    w("")
w("## 5 · Reproducibility")
w("")
w("Blender 4.5 LTS, Cycles on CPU, fixed seed, OpenImageDenoise; the lighting rig, camera model and every parameter are recorded in each manifest (`source.rig`, `source.frame_half_extent_u`, `source.samples`). `bash assets3d/build_all.sh` rebuilds everything from the scripts.")
open(os.path.join(A3D, "RESULTS.md"), "w").write("\n".join(L) + "\n")
print(f"wrote RESULTS.md ({len(L)} lines) and dist/summary.json; assets={len(assets)} checks={len(ver)}")
