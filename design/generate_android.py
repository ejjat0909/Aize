#!/usr/bin/env python3
"""Generate the Android design layer from design/tokens/aize-purple.tokens.json  (plan task P0-05).

Writes (all GENERATED - never edit by hand):
  app/src/main/kotlin/app/aize/design/AizeTokens.kt        Compose colour schemes, route/traffic colours, motion, radii
  app/src/main/assets/style/aize-light.style.json          MapLibre style (Protomaps basemap schema), light
  app/src/main/assets/style/aize-dark.style.json           same, dark

  python3 design/generate_android.py            # (re)generate
  python3 design/generate_android.py --check    # exit 1 if a generated file differs from the tokens (CI gate)

Changing one colour in the tokens therefore changes the app chrome AND the map; --check makes CI fail if someone
forgets to regenerate.  Pure standard library, deterministic output.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
TOKENS = os.path.join(HERE, "tokens", "aize-purple.tokens.json")
OUT_KT = os.path.join(ROOT, "app", "src", "main", "kotlin", "app", "aize", "design", "AizeTokens.kt")
OUT_STYLE = {t: os.path.join(ROOT, "app", "src", "main", "assets", "style", f"aize-{t}.style.json") for t in ("light", "dark")}

# keys of the token theme that are Material 3 ColorScheme parameters; the rest go to AizeExtraColors
M3 = ["primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "secondary", "onSecondary", "secondaryContainer",
      "onSecondaryContainer", "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer", "background", "onBackground",
      "surface", "onSurface", "surfaceVariant", "onSurfaceVariant", "surfaceContainer", "outline", "outlineVariant", "error",
      "onError", "errorContainer", "onErrorContainer", "scrim", "inverseSurface", "inverseOnSurface", "inversePrimary"]
EXTRA = ["success", "warning", "info"]

HEADER_KT = ("// GENERATED by design/generate_android.py from design/tokens/aize-purple.tokens.json - DO NOT EDIT.\n"
             "// Change the tokens, run `python3 design/generate_android.py`, commit both.  CI runs it with --check.\n")


def argb(hexstr):
    h = hexstr.lstrip("#")
    assert len(h) == 6, hexstr
    return "0xFF" + h.upper()


def kt_colors(d, keys):
    return ",\n".join(f"        {k} = Color({argb(d[k])})" for k in keys)


def render_kotlin(t):
    L, D = t["theme"]["light"], t["theme"]["dark"]
    out = [HEADER_KT, "package app.aize.design\n",
           "import androidx.compose.animation.core.CubicBezierEasing",
           "import androidx.compose.material3.ColorScheme",
           "import androidx.compose.material3.darkColorScheme",
           "import androidx.compose.material3.lightColorScheme",
           "import androidx.compose.runtime.Immutable",
           "import androidx.compose.ui.graphics.Color",
           "import androidx.compose.ui.unit.dp\n",
           "object AizeColorSchemes {",
           "    val light: ColorScheme = lightColorScheme(", kt_colors(L, M3), "    )",
           "    val dark: ColorScheme = darkColorScheme(", kt_colors(D, M3), "    )", "}\n",
           "@Immutable", "data class AizeExtraColors(val success: Color, val warning: Color, val info: Color) {", "    companion object {",
           "        val light = AizeExtraColors(" + ", ".join(f"Color({argb(L[k])})" for k in EXTRA) + ")",
           "        val dark = AizeExtraColors(" + ", ".join(f"Color({argb(D[k])})" for k in EXTRA) + ")", "    }", "}\n"]

    # route + traffic as raw ARGB ints: they are consumed by the map (MapLibre wants ints/strings), not by Compose
    out.append("/** ARGB ints for the map layers (MapLibre), per theme. */")
    out.append("object AizeRoute {")
    out.append("    class Palette(val selected: Int, val selectedCasing: Int, val alternative: Int, val alternativeCasing: Int, val passed: Int, val navArrow: Int)")
    for th in ("light", "dark"):
        r = t["route"][th]
        out.append(f"    val {th} = Palette({', '.join(argb(r[k]) + '.toInt()' for k in ('selected', 'selectedCasing', 'alternative', 'alternativeCasing', 'passed', 'navArrow'))})")
    out.append("}\n")
    out.append("object AizeTraffic {")
    out.append("    class Palette(val free: Int, val light: Int, val moderate: Int, val heavy: Int, val standstill: Int)")
    for th in ("light", "dark"):
        r = t["traffic"][th]
        out.append(f"    val {th} = Palette({', '.join(argb(r[k]) + '.toInt()' for k in ('free', 'light', 'moderate', 'heavy', 'standstill'))})")
    out.append("}\n")

    m = t["motion"]
    out.append("/** Durations in ms and cubic-bezier curves from the motion tokens (doc 02 section 7). */")
    out.append("object AizeMotion {")
    for k, v in m["duration"].items():
        out.append(f"    const val {k.upper()}_MS = {int(v)}")
    for k, v in m["easing"].items():
        out.append(f"    val {k[0].upper() + k[1:]} = CubicBezierEasing({', '.join(repr(float(x)) + 'f' for x in v)})")
    out.append("}\n")

    r = t["radius"]
    out.append("object AizeRadius {")
    for k in ("xs", "sm", "md", "lg", "xl"):
        out.append(f"    val {k.upper()} = {int(r[k])}.dp")
    out.append(f"    val BUTTON_SMALL = {int(r['button']['small'])}.dp")
    out.append(f"    val BUTTON_NORMAL = {int(r['button']['normal'])}.dp")
    out.append(f"    val BUTTON_LARGE = {int(r['button']['large'])}.dp")
    out.append(f"    val SHEET = {int(r['sheet'])}.dp")
    out.append(f"    val ALERT = {int(r['alert'])}.dp")
    out.append("}\n")

    s = t["size"]
    out.append("object AizeSize {")
    for k, v in s.items():
        name = "".join("_" + c if c.isupper() else c.upper() for c in k)
        out.append(f"    val {name} = {int(v)}.dp")
    out.append("}")
    return "\n".join(out) + "\n"


# ------------------------------------------------------------------------------------------------ map style
def zoom_stops(stops):
    """[(zoom, px), ...] -> MapLibre interpolate expression."""
    expr = ["interpolate", ["exponential", 1.5], ["zoom"]]
    for z, w in stops:
        expr += [z, w]
    return expr


ROAD_WIDTHS = {  # (fill stops), casing is fill + extra px once the road is wide enough to show it
    "highway": [(5, 0.6), (9, 1.4), (12, 3.0), (14, 5.5), (16, 11), (18, 24), (20, 48)],
    "major_road": [(7, 0.5), (10, 1.2), (12, 2.4), (14, 4.6), (16, 10), (18, 22), (20, 44)],
    "medium_road": [(9, 0.4), (12, 1.2), (14, 3.4), (16, 8), (18, 18), (20, 36)],
    "minor_road": [(11, 0.4), (13, 1.0), (15, 2.8), (16, 6), (18, 14), (20, 28)],
    "other": [(13, 0.4), (15, 1.4), (17, 4), (19, 9)],
}
ROAD_MINZOOM = {"highway": 4, "major_road": 7, "medium_road": 9, "minor_road": 11, "other": 13}
CASING_EXTRA = {"highway": 2.0, "major_road": 1.8, "medium_road": 1.5, "minor_road": 1.2, "other": 0.8}
ROAD_COLOUR_KEY = {"highway": ("highway", "highwayCasing"), "major_road": ("roadMajor", "roadMajorCasing"),
                   "medium_road": ("roadMajor", "roadMajorCasing"), "minor_road": ("roadMinor", "roadMinorCasing"),
                   "other": ("roadMinor", "roadMinorCasing")}


def build_style(t, theme):
    c = t["map"][theme]
    not_tunnel = ["!=", ["get", "is_tunnel"], True]
    layers = [{"id": "background", "type": "background", "paint": {"background-color": c["background"]}},
              {"id": "earth", "type": "fill", "source": "aize", "source-layer": "earth", "paint": {"fill-color": c["land"]}},
              {"id": "landcover", "type": "fill", "source": "aize", "source-layer": "landcover",
               "filter": ["in", ["get", "kind"], ["literal", ["forest", "grassland", "scrub", "barren"]]],
               "paint": {"fill-color": c["park"], "fill-opacity": 0.55}},
              {"id": "landuse-park", "type": "fill", "source": "aize", "source-layer": "landuse",
               "filter": ["in", ["get", "kind"], ["literal", ["park", "nature_reserve", "forest", "cemetery", "golf_course", "playground", "pitch", "zoo", "garden", "grass", "wood"]]],
               "paint": {"fill-color": c["park"]}},
              {"id": "water", "type": "fill", "source": "aize", "source-layer": "water", "paint": {"fill-color": c["water"]}},
              {"id": "buildings", "type": "fill", "source": "aize", "source-layer": "buildings", "minzoom": 13,
               "paint": {"fill-color": c["building"], "fill-opacity": zoom_stops([(13, 0.0), (14.5, 0.9)])}}]
    order = ["other", "minor_road", "medium_road", "major_road", "highway"]   # widest drawn last = on top
    for kind in order:
        fill_key, casing_key = ROAD_COLOUR_KEY[kind]
        flt = ["all", ["==", ["get", "kind"], kind], not_tunnel]
        casing_stops = [(z, w + CASING_EXTRA[kind] if w > 0.9 else w + 0.3) for z, w in ROAD_WIDTHS[kind]]
        base = {"source": "aize", "source-layer": "roads", "minzoom": ROAD_MINZOOM[kind], "filter": flt,
                "layout": {"line-cap": "round", "line-join": "round"}}
        layers.append({**base, "id": f"road-{kind}-casing", "type": "line", "paint": {"line-color": c[casing_key], "line-width": zoom_stops(casing_stops)}})
        layers.append({**base, "id": f"road-{kind}", "type": "line", "paint": {"line-color": c[fill_key], "line-width": zoom_stops(ROAD_WIDTHS[kind])}})
    layers.append({"id": "road-tunnel", "type": "line", "source": "aize", "source-layer": "roads", "minzoom": 12,
                   "filter": ["all", ["==", ["get", "is_tunnel"], True], ["in", ["get", "kind"], ["literal", ["highway", "major_road", "medium_road", "minor_road"]]]],
                   "layout": {"line-cap": "butt"}, "paint": {"line-color": c["roadMajorCasing"], "line-opacity": 0.55, "line-dasharray": [2, 2],
                                                            "line-width": zoom_stops([(12, 1.0), (16, 6), (18, 14)])}})
    # labels
    font_r, font_m = ["Noto Sans Regular"], ["Noto Sans Medium"]
    halo = {"text-color": c["label"], "text-halo-color": c["labelHalo"], "text-halo-width": 1.4}
    layers.append({"id": "label-road", "type": "symbol", "source": "aize", "source-layer": "roads", "minzoom": 14,
                   "filter": ["all", ["has", "name"], ["in", ["get", "kind"], ["literal", ["highway", "major_road", "medium_road", "minor_road"]]]],
                   "layout": {"symbol-placement": "line", "text-field": ["get", "name"], "text-font": font_r, "text-size": zoom_stops([(14, 10), (18, 14)]),
                              "text-letter-spacing": 0.02, "text-max-angle": 30},
                   "paint": halo})
    layers.append({"id": "label-neighbourhood", "type": "symbol", "source": "aize", "source-layer": "places", "minzoom": 12.5, "maxzoom": 17,
                   "filter": ["in", ["get", "kind_detail"], ["literal", ["neighbourhood", "suburb", "quarter", "hamlet", "village"]]],
                   "layout": {"text-field": ["get", "name"], "text-font": font_r, "text-size": zoom_stops([(12, 10), (16, 13)]), "text-transform": "uppercase",
                              "text-letter-spacing": 0.08, "text-max-width": 8},
                   "paint": halo})
    layers.append({"id": "label-locality", "type": "symbol", "source": "aize", "source-layer": "places", "minzoom": 3,
                   "filter": ["==", ["get", "kind"], "locality"],
                   "layout": {"text-field": ["get", "name"], "text-font": font_m, "text-size": zoom_stops([(3, 11), (8, 14), (12, 17), (15, 20)]), "text-max-width": 8,
                              "symbol-sort-key": ["coalesce", ["get", "population_rank"], 0]},
                   "paint": halo})
    return {"version": 8, "name": f"Aize {theme}",
            "metadata": {"generated-by": "design/generate_android.py", "tiles-schema": "Protomaps basemap v4 (OpenStreetMap + Natural Earth)"},
            "glyphs": "asset://glyphs/{fontstack}/{range}.pbf",
            "sources": {"aize": {"type": "vector", "url": "{{TILES_URL}}",
                                 "attribution": "<a href=\"https://www.openstreetmap.org/copyright\">&copy; OpenStreetMap contributors</a> &middot; Protomaps"}},
            "layers": layers}


def render_style(t, theme):
    return json.dumps(build_style(t, theme), indent=1, ensure_ascii=False) + "\n"


def main():
    check = "--check" in sys.argv
    t = json.load(open(TOKENS))
    outputs = {OUT_KT: render_kotlin(t), **{OUT_STYLE[th]: render_style(t, th) for th in OUT_STYLE}}
    stale = []
    for path, text in outputs.items():
        if check:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
                stale.append(os.path.relpath(path, ROOT))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w", encoding="utf-8", newline="\n").write(text)
            print("wrote", os.path.relpath(path, ROOT), f"({len(text):,} bytes)")
    if check:
        if stale:
            print("STALE generated files (run python3 design/generate_android.py):", *stale, sep="\n  ")
            sys.exit(1)
        print(f"OK: {len(outputs)} generated files match the tokens")


if __name__ == "__main__":
    main()
