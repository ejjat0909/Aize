#!/usr/bin/env python3
"""Structure of assets/ (sound prompt sets, skins, Lua map skin, language/search config, profiles).

Static; writes names/counts/sizes only. Translation values and audio/image bytes are never copied.
"""
import collections
import json
import os
import re
import sys
import zipfile


def main(apk, out_json, voicepack_names_txt):
    z = zipfile.ZipFile(apk)
    infos = [i for i in z.infolist() if i.filename.startswith("assets/")]
    out = {}
    # tree (3 levels under assets/)
    tree = collections.OrderedDict()
    for i in infos:
        parts = i.filename.split("/")
        key = "/".join(parts[:4]) if len(parts) > 4 else "/".join(parts[:-1]) or "assets"
        e = tree.setdefault(key, [0, 0, 0])
        e[0] += 1
        e[1] += i.file_size
        e[2] += i.compress_size
    out["assets_tree"] = sorted(([k, *v] for k, v in tree.items()), key=lambda r: -r[2])

    # sound prompt sets
    snd = collections.defaultdict(list)
    for i in infos:
        if i.filename.startswith("assets/res/sound/"):
            parts = i.filename.split("/")
            snd[parts[3]].append((parts[-1], i.file_size))
    out["sound"] = {d: {"files": len(v), "bytes": sum(s for _, s in v), "names": sorted(n for n, _ in v)} for d, v in snd.items()}
    vp = [l.strip() for l in open(voicepack_names_txt) if l.strip()]
    eng = set(out["sound"].get("eng", {}).get("names", []))
    out["sound_vs_community_voicepack_schema"] = {
        "community_valid_names": len(vp), "apk_eng_files": len(eng), "common_files": len(set(out["sound"].get("common", {}).get("names", []))),
        "in_both": sorted(eng & set(vp)), "only_community_schema": sorted(set(vp) - eng), "only_apk_eng": sorted(eng - set(vp)),
    }

    # skins
    skins = [i for i in infos if i.filename.startswith("assets/res/skins/default/")]
    sub = collections.Counter()
    sub_bytes = collections.Counter()
    for i in skins:
        rest = i.filename[len("assets/res/skins/default/"):].split("/")
        k = rest[0] if len(rest) > 1 else "(root files)"
        sub[k] += 1
        sub_bytes[k] += i.file_size
    cars = sorted(os.path.basename(i.filename)[:-4] for i in skins if "/cars/" in i.filename and i.filename.endswith(".obj"))
    st = z.read("assets/res/skins/default/skin_structure.main.lua").decode("utf-8", "replace")
    cats = re.findall(r'^Category\("([^"]+)"\)', st, re.M)
    out["skins"] = {"files": len(skins), "bytes": sum(i.file_size for i in skins), "by_subdir": [[k, sub[k], sub_bytes[k]] for k, _ in sub.most_common()],
                    "car_models_obj": cars, "png_total": sum(1 for i in skins if i.filename.endswith(".png")),
                    "retina_variants": {"@2x": sum(1 for i in skins if "@2x.png" in i.filename), "@3x": sum(1 for i in skins if "@3x.png" in i.filename)},
                    "lua_files": sorted(i.filename.split("assets/res/")[1] for i in infos if i.filename.endswith(".lua")),
                    "map_categories": cats, "zoom_blocks": len(re.findall(r"^\s*Zoom\(", st, re.M)), "last_zoom_blocks": len(re.findall(r"^\s*LastZoom\(", st, re.M)),
                    "zoom_values_used": sorted({int(x) for x in re.findall(r"(?:Last)?Zoom\((\d+)\)", st)}),
                    "structure_lines": st.count("\n")}
    # font sizes block
    m = re.search(r"FontSizes\s*=\s*\{(.*?)\}", st, re.S)
    out["skins"]["font_sizes"] = dict(re.findall(r"(\w+)\s*=\s*([\d.]+)", m.group(1))) if m else {}
    m = re.search(r"ShieldScaleFactors\s*=\s*\{(.*?)\}", st, re.S)
    out["skins"]["shield_scale_factors"] = dict(re.findall(r"(\w+)\s*=\s*([\d.]+)", m.group(1))) if m else {}
    pal = {}
    for mode in ("day", "night"):
        t = z.read(f"assets/res/skins/default/skin_values.{mode}.lua").decode("utf-8", "replace")
        pal[mode] = re.findall(r"^\s*([a-z_][a-z0-9_]*)\s*=\s*rgba?\(0x([0-9A-Fa-f]{6,8})\)", t, re.M)
    out["skins"]["palette_roles"] = {m: len(v) for m, v in pal.items()}
    out["skins"]["palette_sample"] = {m: v[:40] for m, v in pal.items()}

    # language / search config
    langs = []
    for n in ("assets/res/lang.eng", "assets/res/lang.heb", "assets/res/lang.chinese", "assets/res/key_value_tts_strings.txt"):
        data = z.read(n)
        langs.append({"file": os.path.basename(n), "bytes": len(data), "lines": data.count(b"\n"), "key_value": b"=" in data[:4000]})
    out["lang_files"] = langs
    sc = z.read("assets/res/search_conf")
    toks = collections.Counter(t.decode("ascii", "ignore") for t in re.findall(rb"[A-Za-z][A-Za-z _/&\-]{2,28}", sc))
    out["search_conf"] = {"bytes": len(sc), "format": "binary text-buffer (length-prefixed), generated by a SearchServer config tool",
                          "provider_ids": sorted(t for t in toks if t in ("waze", "googlePlaces", "foursquareexplore")),
                          "labels": sorted(t for t in toks if t in ("Waze", "Google Places", "Foursquare", "Around You", "Along Route", "Gas Station", "Parking", "Food", "Coffee")),
                          "category_ids_seen": sorted(t for t in toks if re.fullmatch(r"[a-z_]{3,24}", t) and t not in ("true", "false", "null", "waze"))[:60]}
    out["tts_voices_csv_rows"] = [l.split(",")[0] for l in z.read("assets/res/tts/voices_was_tts.csv").decode().splitlines() if l]
    prof = [i for i in infos if i.filename.startswith("assets/dexopt/")]
    out["baseline_profile"] = [{"file": os.path.basename(i.filename), "bytes": i.file_size} for i in prof]
    out["phenotype"] = [{"file": i.filename, "bytes": i.file_size} for i in infos if "phenotype" in i.filename]
    json.dump(out, open(out_json, "w"), indent=1)
    s = out["sound_vs_community_voicepack_schema"]
    print("assets files", len(infos), "| sound dirs", {d: v["files"] for d, v in out["sound"].items()}, "| skins", out["skins"]["files"], "| categories", len(cats), "| zoom blocks", out["skins"]["zoom_blocks"])
    print("voicepack schema: in both", len(s["in_both"]), "only community", s["only_community_schema"], "only apk eng", len(s["only_apk_eng"]))


if __name__ == "__main__":
    main(*sys.argv[1:4])
